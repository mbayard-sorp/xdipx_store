// ─── Catalog index ────────────────────────────────────────────────────────

interface IndexedProduct {
  gid: string
  numericId: string
  handle: string
  title: string
  vendor: string
  productTypeDial: ProductTypeDial | ''
  productSubtypeDial: string
  dealScore: number | null
  updatedAt: string
  tagline: string
  category: string[]
  hasAccessoryIds: boolean
  hasPairingWhy: boolean
}

interface AdminMetafieldNode { key: string; value: string }
interface AdminProductNode {
  id: string
  handle: string
  title: string
  vendor: string
  status: string
  updatedAt: string
  xdipxMf: { nodes: AdminMetafieldNode[] }
  customMf: { nodes: AdminMetafieldNode[] }
}
interface PageInfo { hasNextPage: boolean; endCursor: string | null }
type FetchResult = { products: { pageInfo: PageInfo; nodes: AdminProductNode[] } }

async function fetchCatalogIndex(): Promise<IndexedProduct[]> {
  const out: IndexedProduct[] = []
  let cursor: string | null = null
  let hasNextPage = true
  let page = 0

  while (hasNextPage) {
    page++
    const data: FetchResult = await adminGraphQL<FetchResult>(`
      query BackfillPairsWithIndex($first: Int!, $after: String) {
        products(first: $first, after: $after, query: "status:active") {
          pageInfo { hasNextPage endCursor }
          nodes {
            id handle title vendor status updatedAt
            xdipxMf: metafields(namespace: "xdipx", first: 100) { nodes { key value } }
            customMf: metafields(namespace: "custom", first: 5) { nodes { key value } }
          }
        }
      }
    `, { first: 50, after: cursor })

    const conn = data.products
    hasNextPage = conn.pageInfo.hasNextPage
    cursor = conn.pageInfo.endCursor

    for (const node of conn.nodes) {
      const xVal = (key: string) => node.xdipxMf.nodes.find(m => m.key === key)?.value ?? ''
      const cVal = (key: string) => node.customMf.nodes.find(m => m.key === key)?.value ?? ''
      const dealScoreRaw = xVal('deal_score')
      const dealScore = dealScoreRaw ? parseFloat(dealScoreRaw) : null
      let category: string[] = []
      const categoryRaw = xVal('category')
      if (categoryRaw.trim().startsWith('[')) {
        try {
          const parsed = JSON.parse(categoryRaw)
          if (Array.isArray(parsed)) category = parsed.filter((s): s is string => typeof s === 'string')
        } catch { /* ignore malformed */ }
      }
      let hasAccessoryIds = false
      const accessoryRaw = xVal('accessory_product_ids')
      if (accessoryRaw.trim().startsWith('[')) {
        try {
          const parsed = JSON.parse(accessoryRaw)
          hasAccessoryIds = Array.isArray(parsed) && parsed.length > 0
        } catch { /* ignore malformed */ }
      }
      let hasPairingWhy = false
      const pairingRaw = xVal('pairing_why')
      if (pairingRaw.trim().startsWith('{')) {
        try {
          const parsed = JSON.parse(pairingRaw)
          hasPairingWhy = parsed && typeof parsed === 'object' && Object.keys(parsed).length > 0
        } catch { /* ignore malformed */ }
      }

      out.push({
        gid:       node.id,
        numericId: node.id.replace('gid://shopify/Product/', ''),
        handle:    node.handle,
        title:     node.title,
        vendor:    node.vendor,
        productTypeDial:    (xVal('product_type_dial') as ProductTypeDial) || '',
        productSubtypeDial: cVal('product_subtype_dial'),
        dealScore,
        updatedAt: node.updatedAt,
        tagline:   xVal('tagline'),
        category,
        hasAccessoryIds,
        hasPairingWhy,
      })
    }

    console.log(`[index] page ${page}: +${conn.nodes.length} products, cumulative=${out.length}`)
  }

  return out
}

// ─── Ranking ──────────────────────────────────────────────────────────────
// xdipx.deal_score desc first (populated on only ~9/4,730 active products —
// a Nalpac-feed-era artifact, not a universal signal), then Shopify's own
// updatedAt desc as the tie-break that does the real ordering work for
// everything else: most-recently-touched product, the best available proxy
// for "currently merchandised" absent a real popularity/sales-rank field.
function rankAnchors(a: IndexedProduct, b: IndexedProduct): number {
  const scoreDiff = (b.dealScore ?? -1) - (a.dealScore ?? -1)
  if (scoreDiff !== 0) return scoreDiff
  return new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime()
}

// ─── Complement resolution ────────────────────────────────────────────────

/** Picks the best candidate in `pool` for a ComplementSpec, preferring an
 *  exact subtype match, falling back to dial-only, excluding `excludeGid`s
 *  already chosen for this anchor. Ranks by dealScore desc within a tier. */
function resolveComplement(
  spec: ComplementSpec,
  pool: IndexedProduct[],
  excludeGids: Set<string>,
): IndexedProduct | null {
  const dialMatches = pool.filter(p => p.productTypeDial === spec.dial && !excludeGids.has(p.gid))
  const rank = (list: IndexedProduct[]) => [...list].sort(rankAnchors)

  if (spec.subtype) {
    const subtypeMatches = rank(dialMatches.filter(p => p.productSubtypeDial === spec.subtype))
    if (subtypeMatches.length > 0) return subtypeMatches[0]!
  }
  const fallback = rank(dialMatches)
  return fallback[0] ?? null
}

// ─── Main ─────────────────────────────────────────────────────────────────

async function main() {
  const args = parseArgs(process.argv)
  console.log(`[backfill-pairswith] mode=${args.apply ? 'APPLY' : 'DRY-RUN'} limit=${args.limit} force=${args.force}`)

  console.log('[backfill-pairswith] building catalog index (ACTIVE products, xdipx + custom metafields)...')
  const index = await fetchCatalogIndex()
  console.log(`[backfill-pairswith] indexed ${index.length} active products`)

  const eligible = index.filter(p => p.productTypeDial && COMPLEMENTS[p.productTypeDial])
  console.log(`[backfill-pairswith] ${eligible.length} products have a product_type_dial with a defined complement mapping`)

  const notAlreadyDone = args.force ? eligible : eligible.filter(p => !(p.hasAccessoryIds && p.hasPairingWhy))
  console.log(`[backfill-pairswith] ${notAlreadyDone.length} not already fully covered (accessory_product_ids + pairing_why)`)

  const anchors = [...notAlreadyDone]
    .sort(rankAnchors)
    .slice(0, args.limit)
  console.log(`[backfill-pairswith] selected ${anchors.length} anchor SKU(s) — top by xdipx.deal_score desc, then Shopify updatedAt desc`)

  let written = 0
  let skippedNoComplement = 0
  const errors: Array<{ handle: string; message: string }> = []

  for (let i = 0; i < anchors.length; i++) {
    const anchor = anchors[i]!
    const specs = COMPLEMENTS[anchor.productTypeDial as ProductTypeDial] ?? []
    const excludeGids = new Set<string>([anchor.gid])
    const picks: IndexedProduct[] = []
    for (const spec of specs) {
      const pick = resolveComplement(spec, index, excludeGids)
      if (pick) {
        picks.push(pick)
        excludeGids.add(pick.gid)
      }
    }

    if (picks.length === 0) {
      skippedNoComplement++
      console.log(`  [${i + 1}/${anchors.length}] SKIP ${anchor.handle} (${anchor.productTypeDial}) — no complement candidates found in catalog`)
      continue
    }

    const accessoryIds = picks.map(p => p.gid)
    console.log(
      `  [${i + 1}/${anchors.length}] ${anchor.handle} (${anchor.productTypeDial}, score=${anchor.dealScore ?? 'n/a'}, updated=${anchor.updatedAt.slice(0, 10)}) -> ` +
      picks.map(p => `${p.handle} (${p.productTypeDial}${p.productSubtypeDial ? `:${p.productSubtypeDial}` : ''})`).join(', '),
    )

    if (!args.apply) continue

    try {
      await updateProductMetafield(anchor.gid, 'accessory_product_ids', JSON.stringify(accessoryIds), 'json')

      const { pairingWhy } = await generatePairingWhyOnly({
        anchor: {
          title: anchor.title,
          ...(anchor.vendor ? { brand: anchor.vendor } : {}),
          ...(anchor.category.length ? { category: anchor.category } : {}),
          ...(anchor.tagline ? { tagline: anchor.tagline } : {}),
          ...(anchor.productTypeDial ? { productTypeDial: anchor.productTypeDial } : {}),
        },
        accessories: picks.map(p => ({ id: p.gid, title: p.title, ...(p.vendor ? { brand: p.vendor } : {}) })),
      })

      if (pairingWhy.length > 0) {
        const blurbs: Record<string, string> = {}
        for (const p of pairingWhy) blurbs[p.accessoryProductId] = p.blurb
        await setPairingWhy(anchor.gid, blurbs, { merge: true })
        console.log(`    ✓ wrote accessory_product_ids (${accessoryIds.length}) + pairing_why (${pairingWhy.length})`)
      } else {
        console.log(`    ✓ wrote accessory_product_ids (${accessoryIds.length}); pairing_why generation returned 0 blurbs`)
      }
      written++
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err)
      errors.push({ handle: anchor.handle, message })
      console.error(`    ✗ ${anchor.handle}: ${message}`)
    }
  }

  console.log('')
  console.log('[backfill-pairswith] summary')
  console.log(`  anchors selected:        ${anchors.length}`)
  console.log(`  skipped (no complement): ${skippedNoComplement}`)
  console.log(`  written:                 ${args.apply ? written : '(dry-run — nothing written)'}`)
  console.log(`  errors:                  ${errors.length}`)
  for (const e of errors) console.log(`    - ${e.handle}: ${e.message}`)

  if (errors.length > 0) process.exit(1)
}

main().catch(err => {
  console.error('[backfill-pairswith] fatal:', err)
  process.exit(1)
})
