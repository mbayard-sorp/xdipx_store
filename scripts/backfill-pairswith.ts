/**
 * Ticket #3451 — one-time backfill for the "Pairs with" storefront surface.
 *
 * PairsWith.tsx, the loader branch in _layout.products.$slug.tsx, and the
 * xdipx.accessory_product_ids / xdipx.pairing_why writers in shopify.server.ts
 * are all already live. The surface just has no data: as of 2026-08-19,
 * accessory_product_ids is non-empty on 10/4,691 products and pairing_why on 6.
 * This script fills both for a top slice of anchor SKUs.
 *
 * Anchor selection: ACTIVE products ranked by xdipx.deal_score (desc) first
 * — but deal_score turns out to be a Nalpac-feed-era artifact populated on
 * only ~9 of 4,730 active products, so it can't carry the ranking alone.
 * Tie-break (i.e. the effective primary signal for the other ~4,721) is
 * Shopify's own updatedAt (desc): most-recently-touched product as the best
 * available proxy for "currently merchandised" absent a real popularity/
 * sales-rank field. Restricted to product_type_dial values with a defined
 * complement mapping below (novelty and book-media are skipped — no natural
 * toy-adjacent accessory), top ~200 taken. Products that already carry BOTH
 * accessory_product_ids and pairing_why are skipped by default (fill-gaps);
 * pass --force to overwrite.
 *
 * Complement map: keyed on product_type_dial (+ product_subtype_dial where
 * it sharpens the pick, e.g. lube's "toy-cleaner" subtype for a cleaner).
 * Editorial judgment, not automated inference — see COMPLEMENTS below.
 *
 * Writes:
 *   1. xdipx.accessory_product_ids (json) via updateProductMetafield — the
 *      curated accessory GID list, in display order.
 *   2. xdipx.pairing_why (json) via setPairingWhy — Emma-voice copy per
 *      accessory GID, generated by generatePairingWhyOnly() in
 *      claude.server.ts, which is a narrow harness around the EXISTING
 *      propose_pairing_why tool + executeRailTool dispatcher from
 *      emma-rail-tools.server.ts (same tool generateRails() uses). No new
 *      copy-generation logic — this only restricts the tool list so the
 *      model can't also propose rails (which would leave unreviewed Sanity
 *      rail drafts for every anchor, out of scope for a metafield backfill).
 *
 * Usage:
 *   npx tsx scripts/backfill-pairswith.ts                  # dry-run, top 200, prints plan
 *   npx tsx scripts/backfill-pairswith.ts --limit=10        # dry-run, first 10 anchors only
 *   npx tsx scripts/backfill-pairswith.ts --apply            # writes to Shopify + Anthropic spend
 *   npx tsx scripts/backfill-pairswith.ts --apply --limit=10 # smoke-test a live run
 *   npx tsx scripts/backfill-pairswith.ts --apply --force    # overwrite anchors that already have data
 *
 * Exit code: 0 on clean run, 1 if any anchor errored.
 */
// MUST be the first import — populates process.env (with override) before any
// downstream module reads it at evaluation time.
